async function findPosts() {
  const posts = await prisma.posts.findMany({
    where: {
      slug: { in: autoGeneratedSlugs },
      status: 'published'
    },
    select: {
      id: true,
      slug: true,
      title: true,
      content: true
    }
  });

  const results = posts.map(p => {
    const content = p.content || '';
    const imgCount = (content.match(/<img/g) || []).length;
    const hasProperStyling = (content.match(/photo-float/g) || []).length >= 2;
    return {
      slug: p.slug,
      imgCount,
      hasProperStyling,
      needsFix: imgCount >= 1 && !hasProperStyling
    };
  });

  console.log('Auto-generated posts status:');
  console.log('='.repeat(70));
  results.forEach(r => {
    const status = r.needsFix ? '❌ NEEDS FIX' : '✅ OK';
    console.log(`${status} ${r.slug} (${r.imgCount} images, styled: ${r.hasProperStyling})`);
  });
  
  const needsFix = results.filter(r => r.needsFix);
  console.log(`\nTotal needing fix: ${needsFix.length}`);
  console.log('\nSlugs to fix:');
  console.log(JSON.stringify(needsFix.map(r => r.slug)));

  await prisma.$disconnect();
}

findPosts();
